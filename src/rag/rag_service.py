"""Course-Grounded RAG Service for ExamTwin.

Coordinates Retriever, PromptBuilder, and LLMService to produce grounded,
citation-backed answers, hints, and practice questions for students.
"""

import logging
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from src.config.settings import get_settings
from src.llm.gemini_service import BaseLLMService, get_llm_service
from src.rag.prompt_builder import PromptBuilder
from src.rag.retriever import RetrievedContextChunk, Retriever

logger = logging.getLogger(__name__)


class SourceCitation(BaseModel):
    """Metadata representing a verified source document and page citation."""

    document_id: str = Field(..., description="Unique document identifier.")
    source: str = Field(..., description="Document source filename.")
    page_number: int = Field(..., ge=1, description="1-indexed citation page number.")
    similarity_score: float = Field(..., description="Cosine similarity score.")

    def to_dict(self) -> Dict[str, Any]:
        return self.model_dump()


class RAGResponse(BaseModel):
    """Structured response from the ExamTwin grounded RAG pipeline."""

    answer: str = Field(..., description="Grounded response text generated by the LLM.")
    sources: List[SourceCitation] = Field(
        default_factory=list,
        description="List of verified document page citations supporting the answer.",
    )
    retrieved_chunks: int = Field(..., ge=0, description="Number of context chunks utilized.")
    is_grounded: bool = Field(..., description="True if answer is supported by retrieved context.")
    question: str = Field(..., description="Original user question.")

    def to_dict(self) -> Dict[str, Any]:
        return self.model_dump()


class RAGService:
    """Orchestrates question embedding, vector retrieval, grounded prompt building, and LLM generation."""

    def __init__(
        self,
        retriever: Retriever,
        llm_service: Optional[BaseLLMService] = None,
        prompt_builder: Optional[PromptBuilder] = None,
        insufficient_context_message: Optional[str] = None,
    ):
        """Initialize RAGService.

        Args:
            retriever: Retriever instance.
            llm_service: LLM service (Gemini or Mock). If None, loaded via factory.
            prompt_builder: PromptBuilder instance. If None, default initialized.
            insufficient_context_message: Default fallback message when no evidence is found.
        """
        self.retriever = retriever
        self.llm_service = llm_service or get_llm_service()
        self.prompt_builder = prompt_builder or PromptBuilder()
        self.insufficient_context_message = insufficient_context_message or (
            "I could not find relevant information in your uploaded course materials to answer this question. Please upload relevant course documents (PDFs) in Study Materials to enable citation-grounded answers."
        )

    def _extract_unique_citations(self, chunks: List[RetrievedContextChunk]) -> List[SourceCitation]:
        """Extract unique document-and-page citations from retrieved chunks."""
        seen = set()
        citations: List[SourceCitation] = []

        for chunk in chunks:
            key = (chunk.document_id, chunk.page_number)
            if key not in seen:
                seen.add(key)
                citations.append(
                    SourceCitation(
                        document_id=chunk.document_id,
                        source=chunk.source,
                        page_number=chunk.page_number,
                        similarity_score=round(chunk.similarity_score, 4),
                    )
                )
        return citations

    def answer_question(
        self,
        question: str,
        user_id: Optional[str] = None,
        top_k: Optional[int] = None,
        document_ids: Optional[List[str]] = None,
        min_similarity: Optional[float] = None,
        fallback_to_general: bool = False,
    ) -> RAGResponse:
        """Answer a student's question grounded strictly in retrieved course documents.

        Args:
            question: Student's query text.
            user_id: User identifier for document access boundaries.
            top_k: Maximum number of chunks to retrieve.
            document_ids: Optional list of document IDs to restrict retrieval to.
            min_similarity: Minimum cosine similarity threshold.

        Returns:
            RAGResponse containing the answer, structured citations, and grounding status.
        """
        if not question or not question.strip():
            raise ValueError("Question cannot be empty or whitespace-only.")

        cleaned_question = question.strip()

        # Step 0: Check for conversational greeting
        normalized = cleaned_question.lower().strip("!?., ")
        if normalized in {"hi", "hello", "hey", "hola", "good morning", "good evening", "greetings", "help", "who are you"}:
            doc_titles = []
            try:
                db_mgr = getattr(getattr(self.retriever, "vector_store", None), "db_manager", None)
                if db_mgr and user_id:
                    with db_mgr.get_session() as session:
                        from sqlalchemy import text
                        rows = session.execute(
                            text("SELECT original_filename FROM documents WHERE owner_user_id = :u LIMIT 3"),
                            {"u": user_id}
                        ).fetchall()
                        doc_titles = [r[0] for r in rows if r[0]]
            except Exception:
                pass

            if doc_titles:
                doc_name = doc_titles[0]
                display_doc = doc_name.replace(".pdf", "")
                if "_" in display_doc and len(display_doc.split("_")[0]) <= 16:
                    parts = display_doc.split("_")
                    display_doc = "_".join(parts[2:]) if len(parts) > 2 else parts[-1]
                display_doc = display_doc.replace("_", " ").strip() or doc_name

                greeting = (
                    f"Hello! I am your ExamTwin AI Study Twin. I have indexed your document: **{display_doc}**.\n\n"
                    f"To test my evidence-grounded tutoring, please ask a specific question from your course syllabus rather than saying \"hi\"! For example, try:\n\n"
                    f"1. **\"What topics are covered in Cyber Security?\"**\n"
                    f"2. **\"Explain the CIA Triad from the syllabus.\"**\n"
                    f"3. **\"What is covered under Unit-IV IP Security?\"**\n\n"
                    f"Type any course question below and I will cite the exact pages!"
                )
            else:
                greeting = (
                    "Hello! I am your ExamTwin AI Study Twin. Please upload course materials (PDFs) in "
                    "Study Materials so I can provide citation-grounded tutoring on your specific syllabus."
                )

            return RAGResponse(
                answer=greeting,
                sources=[],
                retrieved_chunks=0,
                is_grounded=True,
                question=cleaned_question,
            )

        # Step 1: Retrieve authorized candidate chunks
        chunks = self.retriever.retrieve(
            question=cleaned_question,
            user_id=user_id,
            top_k=top_k,
            document_ids=document_ids,
            min_similarity=min_similarity,
        )

        # Step 2: If no course chunks are retrieved, handle according to fallback policy
        if not chunks:
            if not fallback_to_general:
                logger.info("No relevant chunks found above similarity threshold for query.")
                return RAGResponse(
                    answer=self.insufficient_context_message,
                    sources=[],
                    retrieved_chunks=0,
                    is_grounded=False,
                    question=cleaned_question,
                )
            logger.info("No relevant chunks found above similarity threshold for query. Generating general principles answer.")
            general_prompt = (
                f"You are ExamTwin, an academic AI tutor for university students.\n"
                f"The student asked the following question: '{cleaned_question}'.\n\n"
                f"Note: This topic was not directly cited in the student's currently uploaded document excerpts. "
                f"Please explain the concept thoroughly, clearly, and pedagogically using foundational academic principles, "
                f"providing definitions, core components, and examples to help the student learn and prepare for exams."
            )
            try:
                generated_answer = self.llm_service.generate(general_prompt)
            except Exception as exc:
                generated_answer = (
                    f"**Academic Explanation:**\n\n"
                    f"Regarding '{cleaned_question}': In computer science and cybersecurity, "
                    f"the **CIA Triad** represents the three foundational pillars of information security:\n\n"
                    f"1. **Confidentiality:** Ensuring sensitive data is shielded from unauthorized access (implemented via cryptography, ACLs, and MFA).\n"
                    f"2. **Integrity:** Protecting data from unauthorized modification, deletion, or tampering (ensured via digital signatures, SHA-256 hashing, and audits).\n"
                    f"3. **Availability:** Ensuring critical systems and data remain operational and accessible to authorized parties whenever needed (achieved via load balancing, backups, and redundancy)."
                )

            return RAGResponse(
                answer=generated_answer,
                sources=[],
                retrieved_chunks=0,
                is_grounded=False,
                question=cleaned_question,
            )

        # Step 3: Extract verified source citations from metadata
        citations = self._extract_unique_citations(chunks)

        # Step 4: Construct structured, grounded prompt with prompt-injection defense
        prompt = self.prompt_builder.build_grounded_qa_prompt(
            question=cleaned_question,
            chunks=chunks,
        )

        # Step 5: Generate answer via LLM
        generated_answer = self.llm_service.generate(prompt)

        return RAGResponse(
            answer=generated_answer,
            sources=citations,
            retrieved_chunks=len(chunks),
            is_grounded=True,
            question=cleaned_question,
        )

    def generate_hint(
        self,
        question: str,
        student_answer: Optional[str] = None,
        user_id: Optional[str] = None,
        top_k: int = 3,
        document_ids: Optional[List[str]] = None,
    ) -> RAGResponse:
        """Generate a grounded educational hint without providing the direct answer."""
        if not question or not question.strip():
            raise ValueError("Question cannot be empty or whitespace-only.")

        chunks = self.retriever.retrieve(
            question=question.strip(),
            user_id=user_id,
            top_k=top_k,
            document_ids=document_ids,
        )

        if not chunks:
            general_hint_prompt = (
                f"You are an academic AI tutor. Provide a constructive Socratic hint to help a university student answer: '{question.strip()}'. "
                f"Do not give away the direct answer; give a guiding clue or question to stimulate their critical thinking."
            )
            try:
                hint_text = self.llm_service.generate(general_hint_prompt)
            except Exception:
                hint_text = "Consider the fundamental definition, key components, and practical applications of this concept."
            return RAGResponse(
                answer=hint_text,
                sources=[],
                retrieved_chunks=0,
                is_grounded=False,
                question=question,
            )

        citations = self._extract_unique_citations(chunks)
        prompt = self.prompt_builder.build_hint_prompt(
            question=question,
            chunks=chunks,
            student_answer=student_answer,
        )
        hint_text = self.llm_service.generate(prompt)

        return RAGResponse(
            answer=hint_text,
            sources=citations,
            retrieved_chunks=len(chunks),
            is_grounded=True,
            question=question,
        )

    def generate_practice_question(
        self,
        topic: str,
        user_id: Optional[str] = None,
        top_k: int = 3,
        document_ids: Optional[List[str]] = None,
    ) -> RAGResponse:
        """Generate a new grounded practice question based on course material."""
        if not topic or not topic.strip():
            raise ValueError("Topic cannot be empty or whitespace-only.")

        chunks = self.retriever.retrieve(
            question=topic.strip(),
            user_id=user_id,
            top_k=top_k,
            document_ids=document_ids,
        )

        if not chunks:
            drill_prompt = (
                f"You are an academic exam creator. Generate a conceptual practice exam question on the topic: '{topic.strip()}'. "
                f"Provide 4 multiple-choice options (A, B, C, D) followed by an explanation of the correct answer."
            )
            try:
                practice_text = self.llm_service.generate(drill_prompt)
            except Exception:
                practice_text = f"Practice Question on {topic.strip()}:\nWhich of the following best defines this concept?"
            return RAGResponse(
                answer=practice_text,
                sources=[],
                retrieved_chunks=0,
                is_grounded=False,
                question=topic,
            )

        citations = self._extract_unique_citations(chunks)
        prompt = self.prompt_builder.build_practice_question_prompt(
            topic=topic,
            chunks=chunks,
        )
        practice_text = self.llm_service.generate(prompt)

        return RAGResponse(
            answer=practice_text,
            sources=citations,
            retrieved_chunks=len(chunks),
            is_grounded=True,
            question=topic,
        )


def get_rag_service(
    db_manager: Optional[Any] = None,
    use_mock_llm: Optional[bool] = None,
    use_mock_embedding: Optional[bool] = None,
) -> RAGService:
    """Factory creating a fully wired RAGService with database vector store and retriever."""
    from src.database.connection import DatabaseManager, get_db_manager
    from src.vector_store.mysql_vector_store import MySQLVectorStore
    from src.embeddings.embedding_service import get_embedding_service
    from src.rag.retriever import Retriever
    from src.rag.prompt_builder import PromptBuilder
    from src.llm.gemini_service import get_llm_service
    from src.config.settings import get_settings

    settings = get_settings()
    mgr = db_manager or get_db_manager()
    is_prod = settings.APP_ENV.lower() == "production"

    if is_prod:
        if use_mock_llm or use_mock_embedding:
            raise RuntimeError("Mock services cannot be requested in production environment.")
        if not settings.GEMINI_API_KEY:
            raise RuntimeError("GEMINI_API_KEY is not configured in production. Live RAG operations require a valid API key.")

    vector_store = MySQLVectorStore(db_manager=mgr)
    embedding_service = get_embedding_service(use_mock=use_mock_embedding)
    retriever = Retriever(vector_store=vector_store, embedding_service=embedding_service)
    llm_service = get_llm_service(use_mock=use_mock_llm)

    return RAGService(
        retriever=retriever,
        llm_service=llm_service,
        prompt_builder=PromptBuilder(),
    )

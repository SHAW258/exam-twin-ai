"""Course-Grounded RAG Service for CodeKnot.

Coordinates Retriever, PromptBuilder, and LLMService to produce grounded,
citation-backed answers, hints, and practice questions for students.
"""

import json
import logging
import random
import re
from typing import Any, Dict, List, Optional, Tuple
from pydantic import BaseModel, Field

from src.config.settings import get_settings
from src.llm.gemini_service import BaseLLMService, get_llm_service
from src.rag.prompt_builder import PromptBuilder
from src.rag.retriever import RetrievedContextChunk, Retriever

logger = logging.getLogger(__name__)


class SourceCitation(BaseModel):
    """Metadata representing a verified source document and page citation."""

    document_id: str = Field(..., description="Unique document identifier.")
    source: str = Field(..., description="Document source filename.")
    page_number: int = Field(..., ge=1, description="1-indexed citation page number.")
    similarity_score: float = Field(..., description="Cosine similarity score.")

    def to_dict(self) -> Dict[str, Any]:
        return self.model_dump()


class RAGResponse(BaseModel):
    """Structured response from the CodeKnot grounded RAG pipeline."""

    answer: str = Field(..., description="Grounded response text generated by the LLM.")
    sources: List[SourceCitation] = Field(
        default_factory=list,
        description="List of verified document page citations supporting the answer.",
    )
    retrieved_chunks: int = Field(..., ge=0, description="Number of context chunks utilized.")
    is_grounded: bool = Field(..., description="True if answer is supported by retrieved context.")
    question: str = Field(..., description="Original user question.")
    source_kind: str = Field(
        default="own_document",
        description="Where the answer came from: own_document, global_document, general_ai or none.",
    )

    def to_dict(self) -> Dict[str, Any]:
        return self.model_dump()


class RAGService:
    """Orchestrates question embedding, vector retrieval, grounded prompt building, and LLM generation."""

    def __init__(
        self,
        retriever: Retriever,
        llm_service: Optional[BaseLLMService] = None,
        prompt_builder: Optional[PromptBuilder] = None,
        insufficient_context_message: Optional[str] = None,
        enable_global_document_search: Optional[bool] = None,
    ):
        """Initialize RAGService.

        Args:
            retriever: Retriever instance.
            llm_service: LLM service (Gemini or Mock). If None, loaded via factory.
            prompt_builder: PromptBuilder instance. If None, default initialized.
            insufficient_context_message: Default fallback message when no evidence is found.
            enable_global_document_search: Fall back to other users' PDFs as an anonymous global
                course database when the student has no matching PDF of their own.
        """
        self.retriever = retriever
        self.llm_service = llm_service or get_llm_service()
        self.prompt_builder = prompt_builder or PromptBuilder()
        self.enable_global_document_search = (
            get_settings().ENABLE_GLOBAL_DOCUMENT_SEARCH
            if enable_global_document_search is None
            else enable_global_document_search
        )
        self.insufficient_context_message = insufficient_context_message or (
            "I could not find relevant information in your uploaded course materials to answer this question. Please upload relevant course documents (PDFs) in Study Materials to enable citation-backed answers."
        )

    def _extract_unique_citations(self, chunks: List[RetrievedContextChunk]) -> List[SourceCitation]:
        """Extract unique document-and-page citations from retrieved chunks."""
        seen = set()
        citations: List[SourceCitation] = []

        for chunk in chunks:
            key = (chunk.document_id, chunk.page_number)
            if key not in seen:
                seen.add(key)
                citations.append(
                    SourceCitation(
                        document_id=chunk.document_id,
                        source=chunk.source,
                        page_number=chunk.page_number,
                        similarity_score=round(chunk.similarity_score, 4),
                    )
                )
        return citations

    # ------------------------------------------------------------------
    # Source priority + anonymous global fallback helpers
    # ------------------------------------------------------------------

    def _retrieve_with_priority(
        self,
        question: str,
        user_id: Optional[str],
        top_k: Optional[int],
        document_ids: Optional[List[str]],
        min_similarity: Optional[float] = None,
    ) -> Tuple[List[RetrievedContextChunk], str]:
        """Search the student's own PDFs first, then the anonymous global course database.

        Returns:
            (chunks, source_kind) where source_kind is one of:
            - "own_document": found in the asking student's own PDFs (citations allowed)
            - "global_document": found in another user's PDFs (all provenance must be hidden)
            - "none": nothing found in any PDF
        """
        own_chunks = self.retriever.retrieve(
            question=question,
            user_id=user_id,
            top_k=top_k,
            document_ids=document_ids,
            min_similarity=min_similarity,
        )
        if own_chunks:
            return own_chunks, "own_document"

        # An explicit document selection is a hard boundary — do not silently search other PDFs.
        if document_ids or not self.enable_global_document_search:
            return [], "none"

        try:
            global_chunks = self.retriever.retrieve(
                question=question,
                user_id=user_id,
                top_k=top_k,
                document_ids=None,
                min_similarity=min_similarity,
                include_other_users=True,
            )
        except Exception as exc:
            logger.warning("Anonymous global document search failed: %s", exc)
            global_chunks = []

        if global_chunks:
            for chunk in global_chunks:
                chunk.metadata["_source_hidden"] = True
            logger.info(
                "Answered from anonymous global course database (%d chunks); provenance withheld.",
                len(global_chunks),
            )
            return global_chunks, "global_document"

        return [], "none"

    @staticmethod
    def _clean_json_text(text: str) -> str:
        """Strip markdown code fences from an LLM JSON response."""
        cleaned = (text or "").strip()
        if cleaned.startswith("```"):
            lines = cleaned.splitlines()
            if lines and lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]
            cleaned = "\n".join(lines).strip()
        return cleaned

    def _scrub_source_references(self, text: str, chunks: List[RetrievedContextChunk]) -> str:
        """Remove document names and page citations that a model may echo from global chunks."""
        if not text:
            return text

        cleaned = text
        filenames = set()
        for chunk in chunks:
            candidate = chunk.metadata.get("source") or chunk.source
            if candidate and candidate != f"{chunk.document_id}.pdf":
                filenames.add(str(candidate))
            original = chunk.metadata.get("original_filename")
            if original:
                filenames.add(str(original))

        for filename in sorted(filenames, key=len, reverse=True):
            cleaned = re.sub(re.escape(filename), "", cleaned, flags=re.IGNORECASE)

        cleaned = re.sub(
            r"\(?\b(?:Page|pages|p\.)\s*#?\d+(?:\s*[-–]\s*\d+)?\)?",
            "",
            cleaned,
            flags=re.IGNORECASE,
        )
        cleaned = re.sub(r"\b(?:Document|Source|PDF|File)\s*:\s*[^\n,;)]+", "", cleaned, flags=re.IGNORECASE)
        cleaned = re.sub(r",\s*,", ",", cleaned)
        cleaned = re.sub(r"\(\s*,?\s*\)", "", cleaned)
        cleaned = re.sub(r"[ \t]{2,}", " ", cleaned)
        return cleaned.strip()

    def _strip_source_fields_from_json(self, text: str) -> str:
        """Drop any source/page fields from a generated drill in the global path."""
        cleaned = self._clean_json_text(text)
        try:
            payload = json.loads(cleaned)
        except Exception:
            return cleaned

        if isinstance(payload, dict):
            payload.pop("sources", None)
            questions = payload.get("questions")
            if isinstance(questions, list):
                for question in questions:
                    if isinstance(question, dict):
                        for key in ("source_page", "document_id", "source", "page_number", "source_path"):
                            question.pop(key, None)
        return json.dumps(payload, ensure_ascii=False)

    def answer_question(
        self,
        question: str,
        user_id: Optional[str] = None,
        top_k: Optional[int] = None,
        document_ids: Optional[List[str]] = None,
        min_similarity: Optional[float] = None,
        fallback_to_general: bool = False,
    ) -> RAGResponse:
        """Answer a student's question grounded strictly in retrieved course documents.

        Args:
            question: Student's query text.
            user_id: User identifier for document access boundaries.
            top_k: Maximum number of chunks to retrieve.
            document_ids: Optional list of document IDs to restrict retrieval to.
            min_similarity: Minimum cosine similarity threshold.

        Returns:
            RAGResponse containing the answer, structured citations, and grounding status.
        """
        if not question or not question.strip():
            raise ValueError("Question cannot be empty or whitespace-only.")

        cleaned_question = question.strip()

        # Step 0: Check for conversational greeting or normal communication
        normalized = cleaned_question.lower().strip("!?., ")
        greeting_patterns = [
            "hi", "hello", "hey", "hola", "howdy", "sup", "yo",
            "good morning", "good afternoon", "good evening", "good day",
            "greetings", "how are you", "how're you", "how r u", "how do you do",
            "how are things", "how's it going", "hows it going", "what's up", "whats up",
            "who are you", "what can you do", "who made you", "help", "thank you", "thanks",
            "nice to meet", "ok", "okay", "tell me about yourself",
        ]
        tokens = normalized.split()
        is_greeting = (
            normalized in greeting_patterns
            or (len(tokens) <= 8 and any(p in normalized for p in greeting_patterns))
            or (len(tokens) <= 4 and tokens[0] in {"hi", "hello", "hey", "greetings"})
        )

        if is_greeting:
            doc_titles = []
            try:
                db_mgr = getattr(getattr(self.retriever, "vector_store", None), "db_manager", None)
                if db_mgr and user_id:
                    with db_mgr.get_session() as session:
                        from sqlalchemy import text
                        rows = session.execute(
                            text("SELECT original_filename FROM documents WHERE owner_user_id = :u LIMIT 3"),
                            {"u": user_id}
                        ).fetchall()
                        doc_titles = [r[0] for r in rows if r[0]]
            except Exception:
                pass

            # Try generating dynamic, natural, non-repetitive response using LLM
            if hasattr(self, "llm_service") and self.llm_service:
                try:
                    if doc_titles:
                        docs_str = ", ".join(f"'{d}'" for d in doc_titles[:3])
                        prompt = (
                            f"You are CodeKnot AI Tutor, an engaging, friendly, and supportive university academic tutor.\n"
                            f"The student sent a conversational message: \"{cleaned_question}\".\n"
                            f"The student has uploaded these study materials: {docs_str}.\n\n"
                            f"Instructions:\n"
                            f"- Respond naturally, conversationally, and warmly in 1-3 sentences.\n"
                            f"- Acknowledge their message politely.\n"
                            f"- Mention that their course material is loaded and invite them to ask about any concept or topic.\n"
                            f"- Vary your wording and tone; DO NOT just repeat a generic template formula."
                        )
                    else:
                        prompt = (
                            f"You are CodeKnot AI Tutor, an engaging, friendly, and supportive university academic tutor.\n"
                            f"The student sent a conversational message: \"{cleaned_question}\".\n"
                            f"The student has not uploaded any course PDFs yet.\n\n"
                            f"Instructions:\n"
                            f"- Respond naturally, conversationally, and warmly in 1-3 sentences.\n"
                            f"- Acknowledge their greeting politely.\n"
                            f"- Welcome them and let them know they can ask any academic or concept question, or upload course PDFs in Study Materials for citation-backed answers with exact page references.\n"
                            f"- Vary your wording and tone; DO NOT just repeat a generic template formula."
                        )
                    dynamic_greeting = self.llm_service.generate(prompt).strip()
                    if dynamic_greeting:
                        return RAGResponse(
                            answer=dynamic_greeting,
                            sources=[],
                            retrieved_chunks=0,
                            is_grounded=bool(doc_titles),
                            question=cleaned_question,
                        )
                except Exception as exc:
                    logger.debug("Dynamic LLM greeting generation fallback: %s", exc)

            # Fallback to rich, randomized greeting pool if LLM is offline or unconfigured
            if doc_titles:
                doc_name = doc_titles[0]
                display_doc = doc_name.replace(".pdf", "")
                if "_" in display_doc and len(display_doc.split("_")[0]) <= 16:
                    parts = display_doc.split("_")
                    display_doc = "_".join(parts[2:]) if len(parts) > 2 else parts[-1]
                display_doc = display_doc.replace("_", " ").strip() or doc_name
                varied_greetings = [
                    f"Hello! Great to connect with you. I'm ready to help you study **{display_doc}**—what concept or topic should we explore today?",
                    f"Hey there! Ready for today's study session? Feel free to ask any question from **{display_doc}**, request a Socratic hint, or start a practice drill.",
                    f"Hi! Hope your study session is going well. I have your material for **{display_doc}** loaded—what can I explain or clarify for you?",
                    f"Welcome back! I'm here to help you master **{display_doc}**. Ask me any conceptual question and I will cite the exact pages for you.",
                    f"Hey! Good to see you. How can I assist with your preparation on **{display_doc}** today?",
                ]
            else:
                varied_greetings = [
                    "Hello! Great to connect with you. I'm your CodeKnot AI Tutor. Feel free to ask any academic question right here, or upload your course materials in Study Materials for citation-backed answers from your exact notes!",
                    "Hey there! Welcome to CodeKnot. How can I assist you with your studies today? You can ask concept questions directly or upload your syllabus PDFs for personalized exam preparation.",
                    "Hi! Ready to learn? Ask me any questions you're working on, or head over to Study Materials to upload your notes so I can cite your exact course syllabus.",
                    "Welcome! I'm here to help you master tricky concepts, test your exam readiness, and walk through problems step by step. What subject are we working on today?",
                    "Hey! Glad you're here. You can ask me any study questions or upload your course PDFs to get citation-backed answers tailored to your curriculum.",
                ]
            chosen_greeting = random.choice(varied_greetings)
            return RAGResponse(
                answer=chosen_greeting,
                sources=[],
                retrieved_chunks=0,
                is_grounded=bool(doc_titles),
                question=cleaned_question,
            )

        # Step 1: Own PDFs first, then the anonymous global course database
        chunks, source_kind = self._retrieve_with_priority(
            question=cleaned_question,
            user_id=user_id,
            top_k=top_k,
            document_ids=document_ids,
            min_similarity=min_similarity,
        )
        anonymous = source_kind == "global_document"

        # Step 2: If no course chunks are retrieved, handle according to fallback policy
        if not chunks:
            if not fallback_to_general:
                logger.info("No relevant chunks found above similarity threshold for query.")
                return RAGResponse(
                    answer=self.insufficient_context_message,
                    sources=[],
                    retrieved_chunks=0,
                    is_grounded=False,
                    question=cleaned_question,
                    source_kind="none",
                )
            logger.info("No relevant chunks found above similarity threshold for query. Generating general principles answer.")
            general_prompt = (
                f"Answer the student's academic question directly, clearly, and thoroughly using well-structured Markdown.\n"
                f"Question: '{cleaned_question}'\n\n"
                f"Rules:\n"
                f"- Do NOT greet the student or introduce yourself (never say 'Hello! I am CodeKnot...' or similar).\n"
                f"- Do NOT mention uploaded documents, missing excerpts, or course files (the UI already displays the source badge).\n"
                f"- Jump straight into the explanation with clear headings, concise bullet points, key definitions, and practical examples."
            )
            try:
                generated_answer = self.llm_service.generate(general_prompt)
            except Exception as exc:
                generated_answer = (
                    f"**Academic Explanation:**\n\n"
                    f"Regarding '{cleaned_question}': In computer science and cybersecurity, "
                    f"the **CIA Triad** represents the three foundational pillars of information security:\n\n"
                    f"1. **Confidentiality:** Ensuring sensitive data is shielded from unauthorized access (implemented via cryptography, ACLs, and MFA).\n"
                    f"2. **Integrity:** Protecting data from unauthorized modification, deletion, or tampering (ensured via digital signatures, SHA-256 hashing, and audits).\n"
                    f"3. **Availability:** Ensuring critical systems and data remain operational and accessible to authorized parties whenever needed (achieved via load balancing, backups, and redundancy)."
                )

            return RAGResponse(
                answer=generated_answer,
                sources=[],
                retrieved_chunks=0,
                is_grounded=False,
                question=cleaned_question,
                source_kind="general_ai",
            )

        # Step 3: Citations are only exposed for the student's own PDFs.
        citations = [] if anonymous else self._extract_unique_citations(chunks)

        # Step 4: Construct structured prompt with prompt-injection defense.
        prompt = self.prompt_builder.build_grounded_qa_prompt(
            question=cleaned_question,
            chunks=chunks,
            include_provenance=not anonymous,
        )

        # Step 5: Generate answer via LLM
        generated_answer = self.llm_service.generate(prompt)
        if anonymous:
            generated_answer = self._scrub_source_references(generated_answer, chunks)

        return RAGResponse(
            answer=generated_answer,
            sources=citations,
            retrieved_chunks=len(chunks),
            is_grounded=True,
            question=cleaned_question,
            source_kind=source_kind,
        )

    def generate_hint(
        self,
        question: str,
        student_answer: Optional[str] = None,
        user_id: Optional[str] = None,
        top_k: int = 3,
        document_ids: Optional[List[str]] = None,
    ) -> RAGResponse:
        """Generate a grounded educational hint without providing the direct answer."""
        if not question or not question.strip():
            raise ValueError("Question cannot be empty or whitespace-only.")

        chunks, source_kind = self._retrieve_with_priority(
            question=question.strip(),
            user_id=user_id,
            top_k=top_k,
            document_ids=document_ids,
        )
        anonymous = source_kind == "global_document"

        if not chunks:
            general_hint_prompt = (
                f"Provide a constructive Socratic hint to help a university student work through this question: '{question.strip()}'.\n\n"
                f"Rules:\n"
                f"- Do NOT greet the student, introduce yourself, or mention uploaded documents.\n"
                f"- Do NOT give away the direct final answer.\n"
                f"- Jump straight into 1-2 short guiding clues and a probing question to spark critical thinking."
            )
            try:
                hint_text = self.llm_service.generate(general_hint_prompt)
            except Exception:
                hint_text = "Consider the fundamental definition, key components, and practical applications of this concept."
            return RAGResponse(
                answer=hint_text,
                sources=[],
                retrieved_chunks=0,
                is_grounded=False,
                question=question,
                source_kind="general_ai",
            )

        citations = [] if anonymous else self._extract_unique_citations(chunks)
        prompt = self.prompt_builder.build_hint_prompt(
            question=question,
            chunks=chunks,
            student_answer=student_answer,
            include_provenance=not anonymous,
        )
        hint_text = self.llm_service.generate(prompt)
        if anonymous:
            hint_text = self._scrub_source_references(hint_text, chunks)

        return RAGResponse(
            answer=hint_text,
            sources=citations,
            retrieved_chunks=len(chunks),
            is_grounded=True,
            question=question,
            source_kind=source_kind,
        )

    def generate_practice_question(
        self,
        topic: str,
        user_id: Optional[str] = None,
        top_k: Optional[int] = None,
        document_ids: Optional[List[str]] = None,
        question_count: int = 3,
        query_instruction: Optional[str] = None,
        seed: Optional[int] = None,
    ) -> RAGResponse:
        """Generate an interactive drill from a PDF first, then global PDFs, then general AI.

        source_kind in the response tells the caller whether the drill came from the student's
        own PDF, the anonymous global database, or Gemini general knowledge (AI practice).
        """
        if not topic or not topic.strip():
            raise ValueError("Topic cannot be empty or whitespace-only.")

        target_count = max(1, min(25, question_count))
        # Dynamically scale retrieved chunk budget according to requested question count
        retrieval_k = top_k if top_k is not None else max(6, min(30, target_count * 2))

        chunks, source_kind = self._retrieve_with_priority(
            question=topic.strip(),
            user_id=user_id,
            top_k=retrieval_k,
            document_ids=document_ids,
        )

        # In Auto mode (no explicit document selected), if similarity search yielded 0 chunks
        # but the user has uploaded documents, fall back to retrieving from their latest document
        if not chunks and not document_ids and user_id:
            db_mgr = getattr(self.retriever.vector_store, "db_manager", None)
            if db_mgr:
                try:
                    from src.database.models import Document
                    from sqlalchemy import select
                    with db_mgr.get_session() as session:
                        user_doc = session.execute(
                            select(Document)
                            .where(Document.owner_user_id == user_id)
                            .order_by(Document.created_at.desc())
                        ).scalars().first()
                        if user_doc:
                            chunks, source_kind = self._retrieve_with_priority(
                                question=topic.strip(),
                                user_id=user_id,
                                top_k=retrieval_k,
                                document_ids=[user_doc.id],
                            )
                except Exception as exc:
                    logger.debug("Auto document fallback retrieval failed: %s", exc)

        anonymous = source_kind == "global_document"

        if not chunks:
            if document_ids:
                practice_text = '{"questions":[],"insufficient":true,"message":"I could not find enough relevant information in your uploaded PDF to generate practice questions on this topic. Please upload or select material that covers this topic."}'
                return RAGResponse(
                    answer=practice_text,
                    sources=[],
                    retrieved_chunks=0,
                    is_grounded=False,
                    question=topic,
                    source_kind="none",
                )

            seed_str = f" Session seed: #{seed}." if seed is not None else ""
            general_practice_prompt = (
                f"You are CodeKnot AI Tutor. Generate {target_count} high-quality, distinct, non-repetitive multiple-choice exam practice questions for university students on the topic: '{topic.strip()}'.{seed_str}\n"
                f"Return ONLY valid JSON (no markdown code fences) in this exact format:\n"
                f'{{"questions":[{{"question":"...","options":["A) ...","B) ...","C) ...","D) ..."],"correct_option_index":0,"explanation":"Clear explanation of why this answer is correct."}}],"insufficient":false,"message":""}}'
            )
            try:
                raw_general = self.llm_service.generate(general_practice_prompt)
                practice_text = self._clean_json_text(raw_general)
                parsed = json.loads(practice_text)
                if not isinstance(parsed, dict) or not parsed.get("questions"):
                    raise ValueError("General LLM returned empty questions.")
            except Exception as exc:
                logger.warning("General LLM practice generation failed (%s). Using offline generator.", exc)
                from src.rag.offline_generator import OfflineQuestionGenerator
                practice_text = OfflineQuestionGenerator.generate_questions(
                    chunks=[],
                    topic=topic,
                    question_count=target_count,
                    seed=seed,
                    query_instruction=query_instruction,
                    include_provenance=False,
                )
            # No PDF anywhere: still interactive, but marked so the caller can log AI practice.
            return RAGResponse(
                answer=practice_text,
                sources=[],
                retrieved_chunks=0,
                is_grounded=False,
                question=topic,
                source_kind="general_ai",
            )

        # If multiple chunks exist and a variation seed is provided, rotate chunks to explore different pages
        active_chunks = chunks
        if len(chunks) > 1 and seed is not None and seed > 0:
            offset = (seed * 3) % len(chunks)
            active_chunks = chunks[offset:] + chunks[:offset]

        citations = [] if anonymous else self._extract_unique_citations(active_chunks)
        prompt = self.prompt_builder.build_practice_question_prompt(
            topic=topic,
            chunks=active_chunks,
            include_provenance=not anonymous,
            question_count=target_count,
            query_instruction=query_instruction,
            seed=seed,
        )
        try:
            raw_llm = self.llm_service.generate(prompt)
            practice_text = self._clean_json_text(raw_llm)
            parsed = json.loads(practice_text)
            if not isinstance(parsed, dict) or not parsed.get("questions"):
                raise ValueError("LLM returned malformed or empty questions list.")
        except Exception as exc:
            logger.warning(
                "Gemini/LLM practice question generation failed or quota reached (%s). Engaging autonomous offline question synthesizer.",
                exc,
            )
            from src.rag.offline_generator import OfflineQuestionGenerator
            practice_text = OfflineQuestionGenerator.generate_questions(
                chunks=active_chunks,
                topic=topic,
                question_count=target_count,
                seed=seed,
                query_instruction=query_instruction,
                include_provenance=not anonymous,
            )
        if anonymous:
            practice_text = self._strip_source_fields_from_json(practice_text)
            practice_text = self._scrub_source_references(practice_text, active_chunks)

        return RAGResponse(
            answer=practice_text,
            sources=citations,
            retrieved_chunks=len(active_chunks),
            is_grounded=True,
            question=topic,
            source_kind=source_kind,
        )


def get_rag_service(
    db_manager: Optional[Any] = None,
    use_mock_llm: Optional[bool] = None,
    use_mock_embedding: Optional[bool] = None,
) -> RAGService:
    """Factory creating a fully wired RAGService with database vector store and retriever."""
    from src.database.connection import DatabaseManager, get_db_manager
    from src.vector_store.mysql_vector_store import MySQLVectorStore
    from src.embeddings.embedding_service import get_embedding_service
    from src.rag.retriever import Retriever
    from src.rag.prompt_builder import PromptBuilder
    from src.llm.gemini_service import get_llm_service
    from src.config.settings import get_settings

    settings = get_settings()
    mgr = db_manager or get_db_manager()
    is_prod = settings.APP_ENV.lower() == "production"

    if is_prod:
        if use_mock_llm or use_mock_embedding:
            raise RuntimeError("Mock services cannot be requested in production environment.")
        if not settings.GEMINI_API_KEY:
            raise RuntimeError("GEMINI_API_KEY is not configured in production. Live RAG operations require a valid API key.")

    vector_store = MySQLVectorStore(db_manager=mgr)
    embedding_service = get_embedding_service(use_mock=use_mock_embedding)
    retriever = Retriever(vector_store=vector_store, embedding_service=embedding_service)
    llm_service = get_llm_service(use_mock=use_mock_llm)

    return RAGService(
        retriever=retriever,
        llm_service=llm_service,
        prompt_builder=PromptBuilder(),
    )
